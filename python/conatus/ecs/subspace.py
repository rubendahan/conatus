"""Symmetry subspaces of Fourier × Chebyshev × Fourier states made of reflections and half-period
shifts (docs/SYMMETRIES.md).

Every such operation is **diagonal with signs ±1** on the coefficients:

* RealFourier axis (index i: wavenumber n = i // 2, cos for even i, −sin for odd i):
  half-period shift x → x + L/2 multiplies both by (−1)^n; reflection x → −x multiplies the −sin
  coefficient by −1; reflection-and-shift x → L/2 − x is their product;
* Chebyshev axis on a symmetric interval: reflection y → −y multiplies T_k by (−1)^k;
* each field also carries a sign (how the field transforms, e.g. −ψ under s1).

A group generated by such operations is abelian (all elements diagonal, ±1): its fixed subspace is
the set of coefficients on which every generator acts with +1 (a mask), and its **isotypic
components** are the sets with a given character (the sign of each generator), e.g. four for the
shift-reflect group S = {e, s1, s2, s3} of plane Couette flow (Nagata 1990, Waleffe 2003,
Gibson, Halcrow & Cvitanović 2009, eq. 3.3). A linear operator that commutes with the group is
block diagonal in these components: that is what ``symmetry_breaking_check`` uses.

Algebraic unknowns (tau variables) carry no symmetry label here: they are listed separately and
the caller decides (they are slaved to the fields in a solve).
"""
from __future__ import annotations

from dataclasses import dataclass
from itertools import product as iproduct

import numpy as np

from ..errors import CoordinateError, OptionError, SymmetryError
from ..ir.bases import Chebyshev, RealFourier

__all__ = ["AxisAction", "DiagonalSymmetry", "DiagonalSymmetryGroup", "StateTranslation"]


@dataclass(frozen=True)
class AxisAction:
    """Action along one coordinate: ``shift_half`` (x → x + L/2, Fourier only) and/or
    ``reflect`` (x → −x about the origin of a periodic axis, or y → −y on a symmetric interval)."""
    shift_half: bool = False
    reflect: bool = False

    def signs(self, basis) -> np.ndarray:
        N = basis.size
        s = np.ones(N)
        if isinstance(basis, RealFourier):
            n = np.arange(N) // 2
            if self.shift_half:
                s *= (-1.0) ** n
            if self.reflect:
                s *= np.where(np.arange(N) % 2 == 1, -1.0, 1.0)
            return s
        if isinstance(basis, Chebyshev):
            if self.shift_half:
                raise SymmetryError("half-period shift along a Chebyshev axis",
                                    why="a Chebyshev axis is not periodic: no shift by half a period",
                                    fix="use shift_half only on a RealFourier axis; a Chebyshev axis "
                                        "takes reflect=True (symmetric interval) or nothing")
            if self.reflect:
                a, b = basis.bounds
                if abs(a + b) > 1e-14 * max(abs(a), abs(b)):
                    raise SymmetryError("Chebyshev reflection needs a symmetric interval (-a, a)",
                                        where=f"bounds {basis.bounds}",
                                        fix="centre the Chebyshev axis on 0, e.g. bounds=(-1, 1)")
                s *= (-1.0) ** np.arange(N)
            return s
        raise SymmetryError(f"diagonal symmetry not available for {type(basis).__name__}",
                            fix="diagonal (sign) symmetries act on RealFourier and Chebyshev axes "
                                "only; leave this axis out of the generator's axes")


@dataclass(frozen=True)
class DiagonalSymmetry:
    """One generator: per-coordinate actions {coord name: AxisAction} and per-field signs
    {field name: ±1}. List every field of the state: only the tau variables (inside ``lift``) and
    constants stay unlabelled (outside the fixed subspace mask, named by
    ``DiagonalSymmetryGroup.explain()``); an unlisted field is refused."""
    name: str
    axes: dict
    field_signs: dict

    def explain(self) -> str:
        ax = ", ".join(f"{c}: {'shift L/2 ' if a.shift_half else ''}{'reflect' if a.reflect else ''}".strip()
                       for c, a in self.axes.items())
        fs = ", ".join(f"{k} → {'+' if v > 0 else '−'}" for k, v in self.field_signs.items())
        return f"{self.name}: [{ax}]; fields [{fs}]"


class DiagonalSymmetryGroup:
    """Abelian group of diagonal ±1 symmetries acting on the state vector of an IVPSolver.

    ``solver``: gives the variables, their coefficient shapes and the state layout
    (``system.gather_state``); ``generators``: list of :class:`DiagonalSymmetry`."""

    def __init__(self, solver, generators: list[DiagonalSymmetry]) -> None:
        sysm = solver.system
        host = getattr(sysm, "host", sysm)
        self.generators = list(generators)
        plan = solver.plan
        coords = list(plan.domain.coordsys.coords)
        names = [v.name for v in host.variables]
        fields = set().union(*(g.field_signs for g in generators)) if generators else set()
        for g in generators:
            if set(g.field_signs) != fields:
                raise SymmetryError(f"{g.name}: every generator lists the same fields "
                                    f"({sorted(fields)})",
                                    fix="give every DiagonalSymmetry a field_signs entry for each of "
                                        f"{sorted(fields)} (+1 for an unchanged field)")
            if any(v not in (1, -1) for v in g.field_signs.values()):
                raise SymmetryError(f"{g.name}: field signs must be +1 or -1",
                                    where=f"field_signs = {g.field_signs}",
                                    fix="write +1 (even) or -1 (odd) for each field")
        missing = fields - set(names)
        if missing:
            raise SymmetryError(f"unknown fields {sorted(missing)}",
                                fix=f"the state variables are {names}")
        self.n = host.n
        # Unlisted variables get no label: project() sets them to 0 and the spectra leave them out.
        # That is right for the tau variables only; a forgotten field would be erased silently, so
        # an unlisted variable that is neither lifted in some equation nor a constant (gauge tau,
        # Lagrange multiplier) is refused (review of).
        taus = _tau_variables(getattr(plan, "problem", None))
        if taus is not None:
            forgotten = [v for v in names if v not in fields and v not in taus]
            if forgotten:
                raise SymmetryError(f"field_signs must list every field of the state: {forgotten} "
                                    "missing (only the tau variables, inside lift() or constants, "
                                    "are left unlabelled; an unlisted field would be zeroed by "
                                    "project())",
                                    fix=f"add {forgotten} to every generator's field_signs")
        self.unlabelled = [v for v in names if v not in fields]   # the tau variables
        # state index -> sign under each generator (0 on tau / unlisted entries)
        self.field_entry = np.zeros(self.n, bool)
        self.signs = np.zeros((len(generators), self.n))
        for k, (v, shape) in enumerate(zip(host.variables, host.var_shapes, strict=True)):
            if v.name not in fields:
                continue
            lab = np.arange(1, int(np.prod(shape)) + 1, dtype=float).reshape(shape)
            arrays = [lab if j == k else np.zeros(s) for j, s in enumerate(host.var_shapes)]
            X = np.asarray(host.gather_state(arrays, check_subspace=False)).real
            pos = np.flatnonzero(X)
            flat = X[pos].astype(np.int64) - 1
            self.field_entry[pos] = True
            gshape = shape[len(shape) - len(coords):]
            for gi, g in enumerate(generators):
                sg = np.ones(gshape)
                for ax, c in enumerate(coords):
                    act = g.axes.get(c.name)
                    if act is None or gshape[ax] == 1:
                        continue                    # constant along this axis: sign +1
                    b = plan.domain.basis(c)
                    sh = [1] * len(gshape)
                    sh[ax] = gshape[ax]
                    sg = sg * act.signs(b).reshape(sh)
                sg = g.field_signs[v.name] * np.broadcast_to(sg, shape)
                self.signs[gi, pos] = sg.reshape(-1)[flat]
        # characters: one sign per generator; isotypic masks over field entries
        self.characters = list(iproduct((1, -1), repeat=len(generators)))
        self.isotypic = {ch: self.field_entry & np.all(self.signs == np.asarray(ch)[:, None], axis=0)
                         for ch in self.characters}
        self.mask = self.isotypic[self.characters[0]]            # all +1: the fixed subspace

    # ------------------------------------------------------------------ actions
    def apply(self, gi: int, X):
        """Generator ``gi`` applied to a state (tau entries set to 0)."""
        xp = _xp(X)
        return xp.asarray(self.signs[gi]) * X

    def project(self, X):
        """Orthogonal projection onto the fixed subspace (field entries; taus set to 0)."""
        xp = _xp(X)
        return xp.asarray(self.mask.astype(float)) * X

    def defect(self, X) -> float:
        """‖X − P X‖ / ‖X‖ over the field entries: 0 for a symmetric state."""
        xp = _xp(X)
        f = xp.asarray(self.field_entry.astype(float)) * X
        nrm = float(xp.linalg.norm(f))
        return float(xp.linalg.norm(f - self.project(X))) / nrm if nrm else 0.0

    def explain(self) -> str:
        lines = [f"DiagonalSymmetryGroup: {len(self.generators)} generator(s), order "
                 f"{2 ** len(self.generators)}; fixed subspace {int(self.mask.sum())} of "
                 f"{int(self.field_entry.sum())} field coefficients"]
        lines += ["  " + g.explain() for g in self.generators]
        lines += [f"  isotypic component {ch}: {int(m.sum())} coefficients"
                  for ch, m in self.isotypic.items()]
        lines.append("  not labelled (tau variables and constants, slaved to the fields in every "
                     "solve): " + (", ".join(self.unlabelled) or "none"))
        return "\n".join(lines)


def _tau_variables(problem) -> set | None:
    """Names of the variables that may stay unlabelled: those inside a ``lift(...)`` of some
    equation (the tau variables) and the constants (no coordinate: gauge taus, multipliers).
    None when the plan carries no problem to read them from."""
    if problem is None:
        return None
    from ..ir.expr import Lift
    taus = {v.name for v in problem.variables if v.domain is None or not v.domain.coords}
    for eq in problem.equations:
        for e in eq.lhs.walk():
            if isinstance(e, Lift):
                taus |= {f.name for f in e.free_fields()}
    return taus


class StateTranslation:
    """Generator of the continuous translations along a RealFourier axis, ∂/∂x, acting on the
    field coefficients of an IVPSolver state (tau entries: 0).

    Coefficient index i of the axis: wavenumber n = i // 2, cos(k x) for even i, −sin(k x) for
    odd i, k = 2π n / L. With f = a cos(kx) + b (−sin(kx)), ∂x f = (−k b) cos(kx) + (k a)(−sin(kx)):
    (D X)[cos] = −k X[sin], (D X)[sin] = k X[cos] (the partner entry of the same field and
    mode; 0 when the partner is not stored). Used for the phase conditions of a Newton search in
    the full space (neutral directions ∂x u, ∂z u of an equilibrium)"""

    def __init__(self, solver, coord: str) -> None:
        host = getattr(solver.system, "host", solver.system)
        plan = solver.plan
        coords = list(plan.domain.coordsys.coords)
        names = [c.name for c in coords]
        if coord not in names:
            raise CoordinateError(f"unknown coordinate {coord!r} (have {names})",
                                  fix=f"use one of {names}")
        ax = names.index(coord)
        basis = plan.domain.basis(coords[ax])
        if not isinstance(basis, RealFourier):
            raise OptionError(f"StateTranslation: {coord} is not a RealFourier axis",
                              why="a continuous translation acts on a periodic axis only",
                              fix="translate along a RealFourier coordinate")
        self.coord, self.length = coord, float(basis.length)
        self.n = host.n
        self.src = np.zeros(self.n, np.int64)
        self.fac = np.zeros(self.n)
        for k, shape in enumerate(host.var_shapes):
            size = int(np.prod(shape))
            lab = np.arange(1, size + 1, dtype=float).reshape(shape)
            arrays = [lab if j == k else np.zeros(sh) for j, sh in enumerate(host.var_shapes)]
            X = np.asarray(host.gather_state(arrays, check_subspace=False)).real
            pos = np.flatnonzero(X)
            flat = X[pos].astype(np.int64) - 1
            gshape = shape[len(shape) - len(coords):]
            if gshape[ax] == 1:                       # constant along the axis (mean profiles)
                continue
            where = np.full(size, -1, np.int64)       # flat index -> state position
            where[flat] = pos
            idx = np.unravel_index(flat, shape)
            a = len(shape) - len(coords) + ax         # axis of the coordinate in the array
            i = idx[a]
            kn = 2 * np.pi * (i // 2) / self.length
            partner = list(idx)
            partner[a] = np.where(i % 2 == 0, i + 1, i - 1)
            ok = partner[a] < shape[a]
            partner[a] = np.minimum(partner[a], shape[a] - 1)
            pflat = np.ravel_multi_index(tuple(partner), shape)
            ppos = where[pflat]
            ok &= ppos >= 0
            self.src[pos[ok]] = ppos[ok]
            self.fac[pos[ok]] = np.where(i[ok] % 2 == 0, -kn[ok], kn[ok])
        self._dev: dict = {}

    def apply(self, X):
        """∂/∂x of the state X (NumPy or CuPy), tau entries 0."""
        xp = _xp(X)
        key = id(xp)
        if key not in self._dev:
            self._dev[key] = (xp.asarray(self.src), xp.asarray(self.fac))
        src, fac = self._dev[key]
        return fac * X[src]

    def explain(self) -> str:
        return (f"StateTranslation(∂/∂{self.coord}, L = {self.length:.6g}): "
                f"{int(np.count_nonzero(self.fac))} coefficients paired cos/−sin")


def _xp(X):
    try:
        import cupy
        return cupy.get_array_module(X)
    except ImportError:          # pragma: no cover
        return np
