class Parity(int):
    """+1 (even / symmetric) or -1 (odd / antisymmetric)."""

    def __new__(cls, value: int) -> Parity:
        if value not in (1, -1):
            raise SymmetryError(f"parity must be +1 or -1, got {value!r}", fix='Parity(+1) or Parity(-1)')
        return super().__new__(cls, value)

    def explain(self) -> str:
        return (f"Parity {int(self):+d} ({'even / symmetric' if self == 1 else 'odd / antisymmetric'}): "
                "f(R x) = p R_* f(x) under the declared reflection")

    def __mul__(self, other: Any) -> Any:  # type: ignore[override]
        if isinstance(other, int) and other in (1, -1):
            return Parity(int(self) * int(other))
        return int(self) * other

    __rmul__ = __mul__

    def __neg__(self) -> Parity:  # type: ignore[override]
        return Parity(-int(self))

    def __repr__(self) -> str:
        return "Parity(+1)" if self == 1 else "Parity(-1)"

    def __str__(self) -> str:
        return "even" if self == 1 else "odd"


EVEN, ODD = Parity(1), Parity(-1)


def _as_parity(p: Any) -> Parity:
    return p if isinstance(p, Parity) else Parity(int(p))


class _Z2Generator:
    """Common protocol of the generators of a symmetry subspace (Reflection, AzimuthalMFold).

    A field of parity p under a generator g satisfies f(g x) = p g_* f(x), p = +1 or -1 (a real
    character of the cyclic group generated by g). ``det`` is the determinant of g (-1 for a
    reflection: curls and cross products change sign; +1 for a rotation); ``flips(c)`` says whether
    g_* reverses the frame vector (and the derivative) along coordinate c; ``order`` is the order of
    the group generated by g (2 for a reflection, m0 for a rotation by 2 pi / m0)."""

    det = -1
    order = 2

    def flips(self, coord: Coordinate) -> bool:
        return coord == self.coord


class Reflection(_Z2Generator):
    """Reflection x_c -> 2*about - x_c. ``about=None`` means the centre of the interval.

    Curvilinear systems: the colatitude theta of S2/spherical coordinates (the equatorial
    reflection z -> -z, theta -> pi - theta, about pi/2 only; see ``EquatorialParity``) and the
    axis z of cylindrical coordinates. A reflection of the azimuth through a diameter
    (phi -> -phi) links m and -m and is not implemented (refused)."""

    def __init__(self, coord: Coordinate, about: float | None = None) -> None:
        if not isinstance(coord, Coordinate):
            raise TypeError("Reflection needs a Coordinate")
        cs = coord.system
        if cs.curvilinear:
            equatorial = cs.kind in ("S2", "Spherical") and coord.index == 1
            axial = cs.kind == "Cylindrical" and coord.index == 2
            if not (equatorial or axial):
                raise NotImplementedError(
                    f"reflection of {coord.name} in {cs.kind} coordinates: only the equatorial "
                    "reflection (colatitude theta -> pi - theta, S2/spherical) and the axial "
                    "reflection z -> -z (cylindrical) are implemented; a diameter reflection "
                    "phi -> -phi links m and -m (not implemented), use AzimuthalMFold for m classes")
            if equatorial and about is not None and abs(float(about) - math.pi / 2) > 1e-12:
                raise SymmetryError(f"equatorial reflection: theta -> pi - theta is about pi/2, "
                                    f"got about={about}")
        self.coord = coord
        self.about = None if about is None else float(about)

    @property
    def key(self) -> tuple:
        return ("Reflection", self.coord.key, self.about)

    def __eq__(self, other: object) -> bool:
        return isinstance(other, Reflection) and self.key == other.key

    def __hash__(self) -> int:
        return hash(self.key)

    def centre(self, basis: Basis) -> float:
        """Fixed point on ``basis``; checks that the reflection maps the domain to itself."""
        a, b = basis.bounds
        mid = 0.5 * (a + b)
        if self.about is None:
            return mid
        if basis.periodic:
            return self.about
        if abs(self.about - mid) > 1e-12 * max(1.0, abs(mid)):
            raise SymmetryError(
                f"{self}: interval {basis.bounds} is not symmetric about {self.about} "
                f"(its centre is {mid:g})")
        return self.about

    def mirror(self, pos: float, basis: Basis) -> float:
        x0 = self.centre(basis)
        m = 2 * x0 - pos
        if basis.periodic:
            a, L = basis.bounds[0], basis.length
            m = a + (m - a) % L
        return m

    def is_fixed(self, pos: float, basis: Basis) -> bool:
        m = self.mirror(pos, basis)
        if basis.periodic:
            L = basis.length
            d = abs(m - pos) % L
            return min(d, L - d) < 1e-12 * max(1.0, L)
        return abs(m - pos) < 1e-12 * max(1.0, abs(pos))

    @property
    def equatorial(self) -> bool:
        """True for the equatorial reflection theta -> pi - theta (S2/spherical coordinates)."""
        return self.coord.system.kind in ("S2", "Spherical") and self.coord.index == 1

    def __repr__(self) -> str:
        c = self.coord.name
        if self.equatorial:
            return f"Reflection({c} -> pi - {c}, equatorial)"
        return f"Reflection({c} -> {'-' if self.about in (None, 0.0) else f'{2 * self.about:g} - '}{c}" \
               f"{'' if self.about is not None else ', about centre'})"

    def explain(self) -> str:
        where = "the centre of the interval" if self.about is None else f"{self.coord.name} = {self.about:g}"
        return (f"{self!r}: reflection of {self.coord.name} about {where}; "
                "vector components along it change sign, others do not")


