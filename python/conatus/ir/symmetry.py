def component_parity(p: Parity, tensorsig: tuple, index: tuple[int, ...], R: _Z2Generator) -> Parity:
    """Scalar parity of component ``index`` of a tensor with tensor parity ``p`` (one sign per
    index along a frame vector the generator reverses; none for a rotation)."""
    out = p
    for cs, i in zip(tensorsig, index, strict=True):
        if R.flips(cs.coords[i]):
            out = -out
    return out


def _jacobi_symmetric(b: Basis) -> bool:
    return isinstance(b, Jacobi) and b.a == b.b


def parity_of(e: Expr, R: _Z2Generator, lookup: ParityLookup | None = None) -> Parity | None:
    """Tensor parity of ``e`` under ``R``; None means 'identically zero' (compatible with both)."""
    from . import expr as E

    lookup = lookup or ParityLookup(None)
    cache: dict = {}

    def rec(x: Expr) -> Parity | None:
        if x in cache:
            return cache[x]
        r = _rule(x)
        cache[x] = r
        return r

    def _rule(x: Expr) -> Parity | None:
        if isinstance(x, E.Field):
            if x.domain.has(R.coord):
                R.centre(x.domain.basis(R.coord))  # validates the reflection on this domain
            return lookup(x, R)
        if isinstance(x, E.Constant):
            return None if x.is_zero() else EVEN
        if isinstance(x, E.Parameter):
            return EVEN
        if isinstance(x, E.UnitVector):
            return ODD if R.flips(x.coordsys.coords[x.index]) else EVEN
        if isinstance(x, E.Add):
            ps = [(t, rec(t)) for t in x.args]
            known = [(t, p) for t, p in ps if p is not None]
            if not known:
                return None
            t0, p0 = known[0]
            for t, p in known[1:]:
                if p != p0:
                    raise SymmetryBreakingError(
                        f"term '{t}' is {p} under {R!r} but '{t0}' is {p0}: "
                        "the sum breaks the declared symmetry")
            return p0
        if isinstance(x, (E.Mul, E.Dot, E.Outer)):
            out = EVEN
            for a in x.args:
                p = rec(a)
                if p is None:
                    return None
                out = out * p
            return out
        if isinstance(x, E.Power):
            p = rec(x.args[0])
            if p is None or p == EVEN:
                return p
            ex = x.exponent
            if float(ex).is_integer():
                return EVEN if int(ex) % 2 == 0 else ODD
            raise SymmetryBreakingError(f"'{x}': non-integer power of an odd quantity")
        if isinstance(x, E.UnaryFunction):
            p = rec(x.args[0])
            if p is None:                       # f(0): zero, a constant, or undefined
                f0 = x.value_at_zero
                if f0 is None:
                    raise SymmetryBreakingError(f"'{x}': {x.func}(0) is undefined")
                return None if f0 == 0 else EVEN
            if p == EVEN:
                return EVEN
            if x.parity_kind == "odd":
                return ODD
            if x.parity_kind == "even":
                return EVEN
            raise SymmetryBreakingError(
                f"'{x}': {x.func}() of an odd quantity has no parity under {R!r}")
        if isinstance(x, (E.Conj, E.TimeDerivative, E.Gradient, E.Divergence, E.Laplacian)):
            return rec(x.args[0])
        if isinstance(x, E.Curl):
            p = rec(x.args[0])
            return None if p is None else p * R.det  # pseudo-tensor: sign det(R)
        if isinstance(x, E.Cross):
            pa, pb = rec(x.args[0]), rec(x.args[1])
            if pa is None or pb is None:
                return None
            return pa * pb * R.det                   # a x b is a pseudo-vector: sign det(R)
        if isinstance(x, E.Component):
            p = rec(x.args[0])
            if p is None:
                return None
            return -p if R.flips(x.args[0].tensorsig[0].coords[x.index]) else p
        if isinstance(x, E.Differentiate):
            p = rec(x.args[0])
            if p is None:
                return None
            return -p if R.flips(x.coord) else p
        if isinstance(x, E.Integrate):
            p = rec(x.args[0])
            if p is None:
                return None
            if R.coord in x.coords:
                return EVEN if p == EVEN else None  # odd integrand over a symmetric domain: 0
            return p
        if isinstance(x, E.Interpolate):
            p = rec(x.args[0])
            if p is None or x.coord != R.coord:
                return p
            basis = x.args[0].domain.basis(x.coord)
            if R.is_fixed(x.position, basis):
                return EVEN if p == EVEN else None  # odd quantity vanishes on the mirror plane
            return p  # trace at x0; its image is the trace at the mirror point (see BC check)
        if isinstance(x, E.Lift):
            p = rec(x.args[0])
            if p is None or x.basis.coord != R.coord:
                return p
            if not _jacobi_symmetric(x.basis):
                raise SymmetryBreakingError(f"'{x}': Jacobi(a != b) lift polynomial has no parity")
            k = x.basis.size + x.n
            return p if k % 2 == 0 else -p
        raise NotImplementedError(f"parity rule for {type(x).__name__}")

    return rec(e)
