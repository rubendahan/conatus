class ShiftReflect(_Z2Generator):
    """Shift-and-reflect of a periodic pipe or cylinder: phi -> -phi composed with the
    half-period shift z -> z + Lz/2 of the axis,

        (u_phi, u_r, u_z)(phi, r, z) -> (-u_phi, u_r, u_z)(-phi, r, z + Lz/2)

    (the symmetry S of the pipe travelling waves: Wedin & Kerswell 2004, Pringle, Duguet &
    Kerswell 2009, Willis, Cvitanovic & Avila 2013). ``ShiftReflect(phi, z)`` on
    CylindricalCoordinates. A reflection (det -1: curls and cross products change sign) that
    reverses e_phi and d/dphi; the shift commutes with every z operator.

    On a stored real field (m >= 0) it pairs the coefficients (m, k_z) and (m, -k_z) through a
    complex conjugation: it is real-linear, not complex-linear, so it does not reduce the complex
    group systems; IVPs enforce it by a declared projection after every solve of the step
    (``timestep/symmetry_projection.py``: J read off the transforms, leak monitored and refused
    above its bound), together with the reduced m-fold classes. Cartesian shift-reflect (plane
    Couette S of Nagata) lives in ``conatus.ecs.subspace``."""

    det = -1
    order = 2

    def __init__(self, coord: Coordinate, shift: Coordinate) -> None:
        if not isinstance(coord, Coordinate) or not isinstance(shift, Coordinate):
            raise TypeError("ShiftReflect needs the azimuth and the axis Coordinates: ShiftReflect(phi, z)")
        cs = coord.system
        if not (cs.curvilinear and cs.kind == "Cylindrical" and coord.index == 0
                and shift.system is cs and shift.index == 2):
            raise NotImplementedError(
                "ShiftReflect(phi, z): azimuth and axis of CylindricalCoordinates (pipe, "
                "Taylor-Couette); the Cartesian shift-reflect of plane Couette is "
                "conatus.ecs.subspace (DiagonalSymmetryGroup)")
        self.coord, self.shift = coord, shift
        self.about = 0.0

    @property
    def key(self) -> tuple:
        """Hashable identity (generator kind and the two coordinates)."""
        return ("ShiftReflect", self.coord.key, self.shift.key)

    def __eq__(self, other: object) -> bool:
        return isinstance(other, ShiftReflect) and self.key == other.key

    def __hash__(self) -> int:
        return hash(self.key)

    def centre(self, basis: Basis) -> float:
        """Fixed azimuth of the reflection (phi = 0)."""
        return 0.0

    def mirror(self, pos: float, basis: Basis) -> float:
        """Image of azimuth pos under phi -> -phi, wrapped onto the basis period."""
        a, L = basis.bounds[0], basis.length
        return a + (-pos - a) % L

    def is_fixed(self, pos: float, basis: Basis) -> bool:
        """Always False: the half-period shift moves every point (no fixed plane)."""
        # no point is fixed: the half-period shift moves every z (traces along phi or z are never
        # taken on these plans); refused as a fixed plane
        return False

    def __repr__(self) -> str:
        return f"ShiftReflect({self.coord.name} -> -{self.coord.name}, {self.shift.name} -> {self.shift.name} + L/2)"

    def explain(self) -> str:
        """What the generator does and how it is enforced."""
        return (f"{self!r}: reflection of the azimuth through phi = 0 composed with the half-period "
                f"shift of {self.shift.name}; e_phi components change sign, others do not; "
                "enforced by a declared projection in IVPs (real-linear: m and -m are conjugate)")


class AzimuthalMFold(_Z2Generator):
    """Rotation phi -> phi + 2 pi / m0 about the axis (disk, annulus, cylinder, sphere, shell, ball).

    Polar/spherical frame components are carried by the rotation (g_* e_r(x) = e_r(g x)), so a
    field of parity p has every component in the azimuthal class
    ``p = +1``: m = 0 mod m0 (m0-fold invariant); ``p = -1`` (m0 even): m = m0/2 mod m0
    (the rotation by 2 pi / m0 changes its sign). ``AzimuthalMFold(phi, 2)`` with EVEN / ODD
    keeps the even / odd azimuthal wavenumbers. A rotation preserves orientation (det = +1): curls
    and cross products keep their parity; no frame vector and no derivative is reversed."""

    det = +1

    def __init__(self, coord: Coordinate, m0: int = 2) -> None:
        if not isinstance(coord, Coordinate):
            raise TypeError("AzimuthalMFold needs the azimuth Coordinate")
        cs = coord.system
        if not (cs.curvilinear and cs.kind in ("Polar", "Cylindrical", "S2", "Spherical")
                and coord.index == 0):
            raise NotImplementedError(
                f"AzimuthalMFold({coord.name}): the rotation acts on the azimuth phi of polar, "
                "cylindrical, S2 or spherical coordinates (in Cartesian coordinates use "
                "Reflection / shift symmetries)")
        if int(m0) != m0 or int(m0) < 2:
            raise SymmetryError(f"AzimuthalMFold: m0 must be an integer >= 2, got {m0!r}")
        self.coord, self.m0 = coord, int(m0)
        self.about = None

    @property  # type: ignore[override]
    def order(self) -> int:  # noqa: D102
        return self.m0

    def flips(self, coord: Coordinate) -> bool:
        return False

    @property
    def key(self) -> tuple:
        return ("AzimuthalMFold", self.coord.key, self.m0)

    def __eq__(self, other: object) -> bool:
        return isinstance(other, AzimuthalMFold) and self.key == other.key

    def __hash__(self) -> int:
        return hash(self.key)

    def residue(self, p: Parity) -> int:
        """Azimuthal class of parity p: kept wavenumbers are m = residue (mod m0)."""
        if p == 1:
            return 0
        if self.m0 % 2:
            raise SymmetryError(f"{self!r}: an odd m0 has no sign-changing real character "
                                "(parity -1 needs m0 even)")
        return self.m0 // 2

    def keeps(self, m: int, p: Parity) -> bool:
        """Is azimuthal wavenumber m in the class of parity p?"""
        return (int(m) - self.residue(p)) % self.m0 == 0

    def centre(self, basis: Basis) -> float:
        """Validates the azimuthal basis (Fourier over 2 pi, size a multiple of m0)."""
        if not basis.periodic or abs(basis.length - 2 * math.pi) > 1e-12:
            raise SymmetryError(f"{self!r}: the azimuthal basis must be periodic over 2 pi")
        if basis.size % self.m0:
            raise SymmetryError(f"{self!r}: Nphi = {basis.size} is not a multiple of m0 = {self.m0}")
        return 0.0

    def mirror(self, pos: float, basis: Basis) -> float:
        return (pos + 2 * math.pi / self.m0) % (2 * math.pi)

    def is_fixed(self, pos: float, basis: Basis) -> bool:
        return False

    def __repr__(self) -> str:
        return f"AzimuthalMFold({self.coord.name} -> {self.coord.name} + 2 pi/{self.m0})"

    def explain(self) -> str:
        return (f"{self!r}: rotation by 2 pi/{self.m0} about the axis; parity +1 keeps m = 0 mod "
                f"{self.m0}" + (f", parity -1 keeps m = {self.m0 // 2} mod {self.m0}" if self.m0 % 2 == 0
                                else "") + "; frame components are carried (no sign change)")


def EquatorialParity(coordsys: Any) -> Reflection:
    """Equatorial reflection z -> -z (theta -> pi - theta) of S2 or spherical coordinates: the
    parity (-1)^(l+m) of Y_l^m (spin components: ``u_+ <-> -u_-``).
    Returns ``Reflection(theta, about=pi/2)``; accepts the coordinate system or one of its
    coordinates."""
    from .coords import CoordinateSystem
    if isinstance(coordsys, Coordinate):
        coordsys = coordsys.system
    if not isinstance(coordsys, CoordinateSystem) or coordsys.kind not in ("S2", "Spherical"):
        raise NotImplementedError("EquatorialParity needs S2Coordinates or SphericalCoordinates "
                                  "(Cartesian and cylindrical systems: Reflection(z))")
    return Reflection(coordsys.coords[1], about=math.pi / 2)


