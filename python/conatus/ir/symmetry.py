def _normalize_field_symmetry(sym: Any, generators: tuple[_Z2Generator, ...] | None = None
                              ) -> tuple[tuple[_Z2Generator, Parity], ...]:
    if sym is None:
        return ()
    if isinstance(sym, (Parity, int)):
        if generators is None or len(generators) != 1:
            raise SymmetryError("a bare Parity is only unambiguous with a single reflection; "
                                "give {Reflection: Parity}")
        return ((generators[0], _as_parity(sym)),)
    if isinstance(sym, Mapping):
        out = []
        for r, p in sym.items():
            if not isinstance(r, _Z2Generator):
                raise NotImplementedError(f"symmetry {r!r}: only Reflection and AzimuthalMFold "
                                          "generators are supported")
            out.append((r, _as_parity(p)))
        return tuple(sorted(out, key=lambda rp: repr(rp[0].key)))
    raise TypeError(f"cannot interpret symmetry declaration {sym!r}")


class SymmetrySubspace:
    """Invariant subspace of a group generated by reflections, with field parities.

    ``SymmetrySubspace(Rx, u=EVEN, T=ODD)`` or, with several generators,
    ``SymmetrySubspace(Rx, Rz, u={Rx: EVEN, Rz: ODD}, ...)``. Parities may also be
    declared on the Field itself (``Field(..., symmetry={Rx: ODD})``).
    """

    def __init__(self, *generators: Any, **parities: Any) -> None:
        for g in generators:
            if not isinstance(g, _Z2Generator):
                raise NotImplementedError(f"generator {g!r}: only Reflection and AzimuthalMFold "
                                          "generators are supported")
        if len(set(generators)) != len(generators):
            raise SymmetryError("duplicate generators")
        # ShiftReflect(phi, z) and AzimuthalMFold(phi, m0) both act on phi and generate a
        # dihedral group (S R S = R^-1): their common fixed subspace is well defined (allowed)
        coords = [g.coord for g in generators if not isinstance(g, ShiftReflect)]
        if len(set(coords)) != len(coords):
            raise SymmetryError("two generators acting on the same coordinate: two reflections "
                                "compose to a translation, two rotations to one rotation; not a "
                                "new independent factor")
        self.generators: tuple[_Z2Generator, ...] = tuple(generators)
        self.parities: dict[str, dict[_Z2Generator, Parity]] = {
            name: dict(_normalize_field_symmetry(p, self.generators)) for name, p in parities.items()}
        for _name, ps in self.parities.items():      # a sign under an odd rotation has no meaning
            for g, p in ps.items():
                if isinstance(g, AzimuthalMFold):
                    g.residue(p)

    @property
    def order(self) -> int:
        """Order of the group (product of the generators' orders; 2^k for k reflections)."""
        out = 1
        for g in self.generators:
            out *= g.order
        return out

    def parity(self, field: Field, R: _Z2Generator) -> Parity:
        declared = dict(field.symmetry).get(R)
        here = self.parities.get(field.name, {}).get(R)
        if declared is not None and here is not None and declared != here:
            raise SymmetryError(f"conflicting parities for {field.name} under {R!r}: "
                                f"{declared} on the Field, {here} in the subspace")
        p = declared if declared is not None else here
        if p is None:
            raise SymmetryError(f"parity of field '{field.name}' under {R!r} is not declared")
        return p

    def lookup(self) -> ParityLookup:
        return ParityLookup(self)

    def embed(self, *args: Any) -> Any:
        raise NotImplementedError("E: V_G -> V is not available on the IR subspace; a plan "
                                  "discretized with the symmetry works in V_G directly")

    def project(self, *args: Any) -> Any:
        raise NotImplementedError("P: V -> V_G is not available on the IR subspace; a plan "
                                  "discretized with the symmetry works in V_G directly")

    def symmetry_breaking_check(self, *args: Any) -> Any:
        raise NotImplementedError(
            "symmetry_breaking_check lives on the solution objects: conatus.ecs."
            "symmetry_breaking_check (Cartesian equilibria) and conatus.discretize."
            "curvilinear_symmetry.symmetry_breaking_check (curvilinear EVPs, every isotypic class)")

    def explain(self) -> str:
        kinds = " x ".join(f"Z{g.order}" for g in self.generators) or "trivial"
        lines = [f"Symmetry subspace: {kinds} (order {self.order})"]
        for g in self.generators:
            lines.append(f"  generator: {g.explain()}")
        for name, ps in sorted(self.parities.items()):
            lines.append(f"  {name:10s} " + ", ".join(f"{p} under {r!r}" for r, p in ps.items()))
        lines += [
            "  expected reduction: up to x2 per reflection, x m0 per m0-fold rotation (adapted "
            "bases: parity blocks, kept azimuthal classes, docs/site/tutorials/03_symmetries.md)",
            "  WARNING: computing in the invariant subspace hides symmetry-breaking instabilities; "
            "a symmetric solution is not declared stable before symmetry_breaking_check().",
        ]
        return "\n".join(lines)


class ParityLookup:
    """Callable field -> parity under a reflection (from the subspace and Field declarations)."""

    def __init__(self, sub: SymmetrySubspace | None) -> None:
        self.sub = sub

    def __call__(self, field: Field, R: _Z2Generator) -> Parity:
        if self.sub is not None:
            return self.sub.parity(field, R)
        p = dict(field.symmetry).get(R)
        if p is None:
            raise SymmetryError(f"parity of field '{field.name}' under {R!r} is not declared")
        return p


