"""Symmetry subspaces: declaration and parity propagation (spec §34).

 is IR only: a ``SymmetrySubspace`` is generated by reflections (Z2^k); each
field has a parity per generator; every node propagates parities; problems check
that equations are equivariant and boundary conditions compatible. The adapted
bases (cos/sin, even/odd polynomials) and the E/P operators come with.

Tensor convention: a rank-r field with parity p under a reflection R of
coordinate c satisfies  f(R x) = p · R_*(f)(x),  where R_* flips the sign of each
tensor index along c. Hence component (i1..ir) has scalar parity
p · (-1)^(number of indices equal to c). A true vector (velocity) has p = +1:
under x -> -x, u_x is odd and u_z even.
"""
